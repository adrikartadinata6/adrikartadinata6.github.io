#!/usr/bin/env python3
"""Builds js/search-index.js for the site search.

Reads every page, applies the ID/EN dictionaries from js/script.js (data-i18n) and splits
each page into chunks at its headings. Run again after editing page content:
    python3 tools/build-search-index.py
"""
import copy, json, pathlib, re, subprocess, sys
from bs4 import BeautifulSoup, NavigableString, Tag, Comment

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADS = {"h1", "h2", "h3", "h4"}
SKIP = {"script", "style", "svg", "noscript", "template"}

# translations are declared inside script.js: pull them out with node
src = (ROOT / "js/script.js").read_text(encoding="utf-8").split("\n")
start = next(i for i, l in enumerate(src) if l.strip().startswith("const translations"))
end = next(i for i in range(start, len(src)) if src[i].rstrip() == "  };")
js = "\n".join(src[start:end + 1]).replace("const translations =", "var translations =", 1)
js += "\nconsole.log(JSON.stringify(translations));"
tmp = ROOT / "tools/.tr.js"
tmp.write_text(js, encoding="utf-8")
try:
    TR = json.loads(subprocess.run(["node", str(tmp)], capture_output=True, text=True, check=True).stdout)
finally:
    tmp.unlink(missing_ok=True)

PAGE_TITLES = {
    "index.html": ("Home", "Beranda"), "about.html": ("About", "Tentang"), "skills.html": ("Skills", "Keahlian"),
    "education.html": ("Education", "Pendidikan"), "education-polman.html": ("Education: Polman Bandung", "Pendidikan: Polman Bandung"),
    "projects.html": ("Projects", "Proyek"), "experience.html": ("Experience", "Pengalaman"),
    "certificates.html": ("Certificates", "Sertifikat"), "jurnal.html": ("Journal Library", "Pustaka Jurnal"), "contact.html": ("Contact", "Kontak"),
}


def localise(soup, lang):
    if lang == "id":  # blocks with their own Indonesian text (data-nx-id)
        for el in soup.select("[data-nx-id]"):
            el.string = el["data-nx-id"]
    for el in soup.select("[data-i18n]"):
        v = TR[lang].get(el.get("data-i18n"))
        if isinstance(v, str) and not el.find(True):
            el.string = v
        elif isinstance(v, str):
            el.clear(); el.append(BeautifulSoup(v, "html.parser"))
    return soup


def clean(t):
    return re.sub(r"\s+", " ", t).strip()


def chunks(soup):
    main = soup.find("main")
    if not main:
        return []
    out, cur, sec_id = [], None, ""
    seen = set()

    def new(head, anchor):
        nonlocal cur
        cur = {"h": clean(head), "a": anchor, "t": []}
        out.append(cur)

    new("", "")
    for s in main.descendants:
        if not isinstance(s, NavigableString) or isinstance(s, Comment) or s.parent.name in SKIP or any(p.name in SKIP for p in s.parents if isinstance(p, Tag)):
            continue
        txt = clean(str(s))
        if not txt:
            continue
        head = next((p for p in s.parents if isinstance(p, Tag) and p.name in HEADS), None)
        sec = next((p for p in s.parents if isinstance(p, Tag) and p.name in ("section", "article") and p.get("id")), None)
        if head is not None:
            if id(head) not in seen:
                seen.add(id(head))
                new(head.get_text(" "), (sec.get("id") if sec else "") or head.get("id", ""))
            continue
        if cur["a"] == "" and sec is not None and not cur["h"]:
            cur["a"] = sec.get("id")
        cur["t"].append(txt)
    res = []
    for c in out:
        body = clean(" ".join(c["t"]))
        if c["h"] or len(body) > 30:
            res.append((c["h"], c["a"], body[:700]))
    return res


rows = []
pages = sorted(ROOT.glob("*.html")) + sorted((ROOT / "projects").glob("*.html"))
for p in pages:
    rel = p.relative_to(ROOT).as_posix()
    if rel in ("404.html", "projects/project-template.html"):
        continue
    raw = p.read_text(encoding="utf-8")
    base = BeautifulSoup(raw, "html.parser")
    en = chunks(localise(copy.copy(BeautifulSoup(raw, "html.parser")), "en"))
    idn = chunks(localise(copy.copy(BeautifulSoup(raw, "html.parser")), "id"))
    h1 = base.find("h1")
    t_en, t_id = PAGE_TITLES.get(rel) or (
        (clean(h1.get_text(" ")) if h1 else rel),) * 2
    if len(en) != len(idn):  # structure should be identical; fall back to the EN text if not
        idn = en
    for (he, a, te), (hi, _, ti) in zip(en, idn):
        if not he and not te:
            continue
        rows.append([rel, t_en, t_id, he, hi, a, te, ti])

(ROOT / "js/search-index.js").write_text(
    "/* generated by tools/build-search-index.py - do not edit by hand */\nwindow.__NX_INDEX=" + json.dumps(rows, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8")
print(f"{len(rows)} chunks from {len({r[0] for r in rows})} pages -> js/search-index.js ({(ROOT/'js/search-index.js').stat().st_size//1024} KB)")
